// Helper to pre-generate label evidence
function createMockEvidence(params: {
  boxNo: string;
  partNo: string;
  spec: string;
  batchNo: string;
  qty: number;
  unit: string;
  isBlurry?: boolean;
}) {
  const photoUrl = generateSyntheticLabelImage(params);
  return {
    photoUrl,
    capturedAt: '2026-10-27T08:30:00.000Z',
    capturedBy: '林志遠',
    ocrResult: {
      boxNo: params.boxNo,
      partNo: params.partNo,
      spec: params.spec,
      batchNo: params.batchNo,
      labelQty: params.qty,
      unit: params.unit,
      confidence: params.isBlurry ? 0.62 : 0.98,
      notes: params.isBlurry ? '標籤邊角略有污漬，信心度偏低' : '文字清晰，辨識無誤',
    },
    manualEditHistory: [],
    reviewStatus: (params.isBlurry ? 'PENDING_MANUAL_REVIEW' : 'VERIFIED') as any,
  };
}

